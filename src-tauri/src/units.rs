//! Units of measure: the list each context keeps (a label and a UN/ECE rec. 20 code), the catalog
//! the settings offer codes from, and what older data was printed as.
//!
//! A position carries its code and its label (`Position::unit_label`), so renaming or deleting a
//! unit never changes a created invoice. The XML only gets the code.

use std::sync::OnceLock;

use anyhow::{anyhow, bail, Result};
use en16931::codes::guard;
use serde::{Deserialize, Serialize};

use crate::model::Kind;

/// A unit of a context's list
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Unit {
    /// None while it is new
    pub id: Option<i64>,
    /// The context whose list it is in, fixed once stored
    pub context_id: i64,
    /// UN/ECE rec. 20 code
    pub code: String,
    pub label: String,
}

/// A unit without a place: what a new context starts with
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UnitDef {
    pub code: String,
    pub label: String,
}

/// A rec. 20 / 21 code with its names: the English one of the official list, and a German one for
/// the common codes, which are listed first and offered when nothing is searched for
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CatalogEntry {
    pub code: String,
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub de: Option<String>,
}

#[derive(Deserialize)]
struct CatalogFile {
    units: Vec<CatalogEntry>,
}

/// Generated by `scripts/unit-names.ts`, the file names its source
const CATALOG_JSON: &str = include_str!("../data/unit-names.json");

/// Every code `guard::unit` accepts, with its names: the common ones first, then by code. Read on
/// first use, so a start of the app does not pay for it.
pub fn catalog() -> &'static [CatalogEntry] {
    static CATALOG: OnceLock<Vec<CatalogEntry>> = OnceLock::new();
    CATALOG.get_or_init(|| {
        serde_json::from_str::<CatalogFile>(CATALOG_JSON)
            .expect("data/unit-names.json is valid, a test reads it")
            .units
    })
}

/// What every context starts with: label and code
pub const DEFAULTS: [(&str, &str); 3] = [("C62", "Stk."), ("HUR", "Std."), ("LS", "pauschal")];

/// The defaults as a list to store
pub fn defaults() -> Vec<UnitDef> {
    DEFAULTS
        .iter()
        .map(|(code, label)| UnitDef {
            code: (*code).into(),
            label: (*label).into(),
        })
        .collect()
}

/// What a code was printed as before units had labels. Positions of older data get this label when
/// they are read. A frozen copy of the old table: it is never edited, or created invoices would
/// look different.
pub fn legacy_label(code: &str) -> String {
    match code {
        "C62" | "H87" => "Stk.",
        "HUR" => "Std.",
        "DAY" => "Tag(e)",
        "MON" => "Monat(e)",
        "WEE" => "Woche(n)",
        "KGM" => "kg",
        "LTR" => "l",
        "MTR" => "m",
        "KWH" => "kWh",
        "LS" => "pauschal",
        other => other,
    }
    .to_owned()
}

/// The German name of a code if it has one, else the English one
pub fn catalog_name(code: &str) -> Option<&'static str> {
    catalog()
        .iter()
        .find(|e| e.code == code)
        .map(|e| e.de.as_deref().unwrap_or(&e.name))
}

/// A unit as it may be stored: trimmed, with a code the EN 16931 rules know and a label that none
/// of `others` (the rest of the list) has, case aside. Several labels may share a code.
pub fn check(unit: &UnitDef, others: &[Unit]) -> Result<UnitDef> {
    let label = unit.label.trim();
    if label.is_empty() {
        bail!("Eine Bezeichnung ist erforderlich.");
    }
    // no trimming of the code: the guard names whitespace and case as the problem
    let code = unit.code.as_str();
    guard::unit(code).map_err(|e| anyhow!("Der Code „{code}“ ist nicht zulässig: {e}"))?;
    if others
        .iter()
        .any(|o| o.label.trim().to_lowercase() == label.to_lowercase())
    {
        bail!("Die Bezeichnung „{label}“ gibt es schon.");
    }
    Ok(UnitDef {
        code: code.into(),
        label: label.into(),
    })
}

/// A saved position that uses a unit
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct TemplateRef {
    pub id: i64,
    pub description: String,
    /// None: it is shared by all contexts
    pub context_id: Option<i64>,
}

/// A draft (of an invoice or an offer) with a position that uses a unit
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct DraftRef {
    pub invoice_id: i64,
    pub kind: Kind,
    pub customer: String,
}

/// Where a unit is used by what a change reaches: drafts and saved positions. Created, imported and
/// archived documents are never touched.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize)]
pub struct UnitUsage {
    pub templates: Vec<TemplateRef>,
    pub drafts: Vec<DraftRef>,
}

impl UnitUsage {
    pub fn is_empty(&self) -> bool {
        self.templates.is_empty() && self.drafts.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use en16931::codes::generated::UNIT_CODES;

    use super::*;

    fn listed(label: &str) -> Unit {
        Unit {
            id: Some(1),
            context_id: 1,
            code: "C62".into(),
            label: label.into(),
        }
    }

    fn def(code: &str, label: &str) -> UnitDef {
        UnitDef {
            code: code.into(),
            label: label.into(),
        }
    }

    #[test]
    fn the_catalog_names_exactly_the_codes_the_rules_accept() {
        let named: Vec<&str> = catalog().iter().map(|e| e.code.as_str()).collect();
        let accepted: BTreeSet<&str> = UNIT_CODES.iter().copied().collect();

        let unique: BTreeSet<&str> = named.iter().copied().collect();
        assert_eq!(unique.len(), named.len(), "a code is named twice");
        let missing: Vec<_> = accepted.difference(&unique).collect();
        let extra: Vec<_> = unique.difference(&accepted).collect();
        assert!(
            missing.is_empty() && extra.is_empty(),
            "regenerate data/unit-names.json (scripts/unit-names.ts), missing: {missing:?}, extra: {extra:?}"
        );
        assert!(catalog().iter().all(|e| !e.name.trim().is_empty()));
    }

    #[test]
    fn the_common_codes_come_first_with_a_german_name() {
        let common = catalog().iter().take_while(|e| e.de.is_some()).count();

        assert!(common >= DEFAULTS.len());
        assert!(catalog()[common..].iter().all(|e| e.de.is_none()));
        assert_eq!(catalog_name("HUR"), Some("Stunde"));
        // no German name: the English one
        assert_eq!(catalog_name("ACR"), Some("acre"));
        assert_eq!(catalog_name("nope"), None);
    }

    #[test]
    fn the_defaults_are_in_the_catalog() {
        DEFAULTS
            .iter()
            .for_each(|(code, _)| assert!(catalog_name(code).is_some(), "{code}"));
    }

    #[test]
    fn a_code_in_the_wrong_case_is_refused_with_the_hint() {
        let error = check(&def("kwh", "kWh"), &[]).unwrap_err().to_string();

        assert!(error.contains("KWH"), "{error}");
        assert!(check(&def(" KWH", "kWh"), &[]).is_err());
        assert!(check(&def("KWH", "kWh"), &[]).is_ok());
    }

    #[test]
    fn the_label_is_trimmed_required_and_unique_ignoring_case() {
        let others = [listed("Stk.")];

        assert_eq!(
            check(&def("HUR", "  Std. "), &others).unwrap().label,
            "Std."
        );
        assert!(check(&def("HUR", "  "), &others).is_err());
        assert!(check(&def("HUR", "stk."), &others).is_err());
        // a code may carry several labels
        assert!(check(&def("C62", "Lizenz"), &others).is_ok());
    }

    #[test]
    fn legacy_labels_are_what_the_old_table_printed() {
        let old = [
            ("C62", "Stk."),
            ("H87", "Stk."),
            ("HUR", "Std."),
            ("DAY", "Tag(e)"),
            ("MON", "Monat(e)"),
            ("WEE", "Woche(n)"),
            ("KGM", "kg"),
            ("LTR", "l"),
            ("MTR", "m"),
            ("KWH", "kWh"),
            ("LS", "pauschal"),
            ("XYZ", "XYZ"),
        ];

        old.iter()
            .for_each(|(code, label)| assert_eq!(legacy_label(code), *label, "{code}"));
    }
}
